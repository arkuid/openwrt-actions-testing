#!/bin/sh
# Для python-zope-event
sed -i 's/python-setuptools\/host/python-setuptools/g' feeds/packages/lang/python/python-zope-event/Makefile
sed -i 's/python-setuptools\/host/python-setuptools/g' feeds/packages/lang/python/python-zope-interface/Makefile

# Для exim
sed -i 's/^  DEPENDS:= +USE_GLIBC:libcrypt-compat +libdb47 +libpcre2 $(ICONV_DEPENDS) +BUILD_NLS:libidn2 +BUILD_NLS:libidn$/  DEPENDS:=+libdb47 +libpcre2 $(ICONV_DEPENDS) +BUILD_NLS:libidn2 +BUILD_NLS:libidn/' feeds/packages/mail/exim/Makefile

commits="13945f4fa374419c9025eb03a5c1937b180ca9bf 0cfa434942ac4afeb7127d57a35f04999988fac9 009b883aebc0dea386ce6ae97cdfa9911178e82f"

for commit in $commits; do
    patch_url="https://github.com/openwrt/openwrt/commit/${commit}.patch"
    curl -sL "$patch_url" -o "${commit}.patch"
    
    echo "Применяю патч: ${commit}"
    patch -p1 < "${commit}.patch" 2>/dev/null
done
echo "Применяю патч: c5prov1.patch"
patch -p1 < c5prov1.patch


FILENAME="board-tplink_archer-c5-pro-v1.qca9888"
TARGET_DIR="package/firmware/ipq-wifi/files"

echo "=== Распаковка $FILENAME ==="

# Проверка существования файла
if [ -f "$FILENAME" ]; then
    echo "Файл уже существует: $FILENAME"
    exit 0
fi

# Извлечение base64
echo "Извлекаю данные..."
BASE64_DATA=$(awk -v f="$FILENAME" '
    $0 == "# BEGIN_B64_ " f {start=1; next}
    $0 == "# END_B64_ " f {exit}
    start {printf "%s", $0}
' "$0")

if [ -z "$BASE64_DATA" ]; then
    echo "ОШИБКА: Не найдены base64 данные"
    exit 1
fi

# Декодирование
echo "Декодирую base64..."
echo "$BASE64_DATA" | base64 -d > "$FILENAME"

if [ $? -ne 0 ] || [ ! -f "$FILENAME" ]; then
    echo "ОШИБКА: Не удалось декодировать"
    exit 1
fi

echo "Файл создан: $FILENAME ($(stat -c%s "$FILENAME") байт)"

# Копирование в целевую директорию (ОТНОСИТЕЛЬНЫЙ ПУТЬ!)
echo "Копирую в $TARGET_DIR..."
mkdir -p "$TARGET_DIR"

if cp "$FILENAME" "$TARGET_DIR/"; then
    echo "УСПЕХ: Файл скопирован в $TARGET_DIR"
    ls -la "$TARGET_DIR/$FILENAME"
else
    echo "ВНИМАНИЕ: Не удалось скопировать в $TARGET_DIR"
    echo "   Файл остался в: $(pwd)/$FILENAME"
    exit 1
fi

echo "=== Готово ==="
exit 0

